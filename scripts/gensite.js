#!/usr/bin/env node
/* scripts/gensite.js — generates the structured parts of hphp.ch from their
 * sources. Run after scripts/gendocs.js (ship.sh does both).
 *
 *   docs/libraries/index.html            library hub: popular, search, all
 *   docs/libraries/<name>/index.html     one page per library, four tabs
 *   docs/docs.html                       documentation with topic tabs
 *   docs/lib-<name>.html                 redirects from the old URLs
 *
 * Sources:
 *   packages/lib/<name>/hphp.json        name, version, description, require
 *   docs/libraries/src/<name>.html       <section data-tab="overview|documentation|examples">
 *   LIBS below                           category, tagline, tags, popularity
 *   docs/lang.html, docs/builtins.html, docs/cli.html, docs/pkg.html,
 *   docs/libraries/src/_sqlite.html      documentation tabs
 */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DOCS = path.join(ROOT, "docs");
const LIBDIR = path.join(ROOT, "packages", "lib");
const SRC = path.join(DOCS, "libraries", "src");

/* Libraries that are not part of the language core. `rank` orders the
 * "Popular" row (lower first). Built-in modules such as SQLite are language
 * features and live in the documentation, not here. */
