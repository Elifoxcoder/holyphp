function redirectPage(to, title) {
  return `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>${esc(title)} — moved</title>
<link rel="canonical" href="https://hphp.ch/${to}">
<meta http-equiv="refresh" content="0; url=${to}">
<script>location.replace(${JSON.stringify(to)} + location.hash);</script>
</head><body><p>This page moved to <a href="${to}">${to}</a>.</p></body></html>
`;
}

/* ---------------- documentation ---------------- */

function sectionsOf(html, level = "h2") {
  const main = mainOf(html);
  const re = new RegExp(`(?=<${level}[\\s>])`);
  const parts = main.split(re);
  const intro = parts[0];
  const out = [];
  for (const p of parts.slice(1)) {
    const m = p.match(new RegExp(`<${level}[^>]*>([\\s\\S]*?)<\\/${level}>`));
    if (!m) continue;
    out.push({ title: m[1].replace(/<[^>]+>/g, "").trim(), html: p.trim() });
  }
  return { intro, sections: out };
}

function documentationPage() {
  const groups = [];

  /* Language: one tab per section of lang.html */
  const lang = sectionsOf(read(path.join(DOCS, "lang.html")));
  groups.push({
    title: "Language",
    tabs: lang.sections.map((s) => ({ id: slug(s.title), title: s.title.replace(/&amp;/g, "&"), html: s.html })),
  });

  /* Standard library: one tab per builtin category of builtins.html */
  const bi = read(path.join(DOCS, "builtins.html"));
  const biMain = mainOf(bi);
  const biParts = biMain.split(/(?=<h2 class="bi-group")/).slice(1);
  const stdTabs = [];
  for (const p of biParts) {
    const m = p.match(/<h2 class="bi-group" id="cat-([^"]+)">([^<]*)<span class="muted small">\((\d+)\)<\/span><\/h2>/);
    if (!m) continue;
    const title = m[2].trim().replace(/&amp;/g, "&");
    let html = p.replace(/<h2 class="bi-group"[^>]*>[\s\S]*?<\/h2>/, `<h2>${esc(title)} <span class="muted small">(${m[3]} functions)</span></h2>`);
    html = html.replace(/(<\/div>\s*)+$/, (s) => s);   /* keep rows intact */
    stdTabs.push({ id: "std-" + m[1].replace(/-+$/, ""), title, html, count: +m[3] });
  }
  /* SQLite is built in too */
  const sqliteSrc = path.join(SRC, "_sqlite.html");
  if (fs.existsSync(sqliteSrc)) stdTabs.push({ id: "sqlite", title: "SQLite", html: read(sqliteSrc) });
  const order = ["Strings", "Math", "Arrays", "Regex", "Time", "Hash & encode", "Types & vars", "System & I/O", "HTTP & MySQL", "SQLite", "Predefined constants", "UI (desktop)", "Unsafe / FFI", "Other"];
  stdTabs.sort((a, b) => (order.indexOf(a.title) + 99) % 99 - (order.indexOf(b.title) + 99) % 99);
  groups.push({ title: "Standard library", tabs: stdTabs });

  /* Tooling */
  groups.push({
    title: "Tooling",
    tabs: [
      { id: "command-line", title: "Command line", html: mainOf(read(path.join(DOCS, "cli.html"))).replace(/<h1[\s\S]*?<\/h1>/, "<h2>Command line</h2>") },
      { id: "projects", title: "Projects & packages", html: mainOf(read(path.join(DOCS, "pkg.html"))).replace(/<h1[\s\S]*?<\/h1>/, "<h2>Projects &amp; packages</h2>") },
      { id: "libraries", title: "Libraries ↗", href: "libraries/" },
    ],
  });

  const allTabs = groups.flatMap((g) => g.tabs).filter((t) => !t.href);
  const side = groups.map((g) => `<div class="doc-group"><h3>${esc(g.title)}</h3>${g.tabs.map((t) => t.href
      ? `<a class="doc-link" href="${t.href}">${esc(t.title)}</a>`
      : `<a class="doc-link" href="#${t.id}" data-tab-button="${t.id}">${esc(t.title)}${t.count ? ` <small>${t.count}</small>` : ""}</a>`).join("")}</div>`).join("\n");

  const body = `<main class="site-page doc-page" data-tabs>
<aside class="doc-side" aria-label="Documentation topics">
  <label class="doc-search"><span class="sr-only">Search functions</span><input id="doc-q" type="search" placeholder="Search functions…" autocomplete="off"></label>
  ${side}
</aside>
<div class="doc-body">
  <button class="doc-menu" type="button" aria-label="Topics" onclick="document.querySelector('.doc-side').classList.toggle('open')">☰ Topics</button>
  <section class="tab-panel" data-tab-panel="search-results" hidden><h2>Search results</h2><div id="doc-results"></div></section>
${allTabs.map((t) => `  <section class="tab-panel" data-tab-panel="${t.id}">
${t.html}
  </section>`).join("\n")}
</div>
</main>`;

  const script = TABS_JS + `
<script>
(function () {
  var q = document.getElementById("doc-q"), out = document.getElementById("doc-results");
  var rows = Array.prototype.slice.call(document.querySelectorAll(".doc-body .bi-row[data-name]"));
  var last = "";
  q.addEventListener("input", function () {
    var w = q.value.trim().toLowerCase();
    if (!w) { if (last) window.__showTab(last, true); last = ""; return; }
    if (!last) last = (location.hash.slice(1) || "variables-and-types");
    var hits = rows.filter(function (r) { return r.getAttribute("data-name").indexOf(w) >= 0 || r.textContent.toLowerCase().indexOf(w) >= 0; }).slice(0, 80);
    out.innerHTML = hits.length ? "" : "<p class='muted'>No function matches “" + w.replace(/</g, "&lt;") + "”.</p>";
    hits.forEach(function (r) { out.appendChild(r.cloneNode(true)); });
    document.querySelectorAll("[data-tab-panel]").forEach(function (p) { p.hidden = p.getAttribute("data-tab-panel") !== "search-results"; });
  });
})();
</script>`;
  return page({
    title: "Documentation — HolyPHP",
    description: "HolyPHP documentation: the language (types, functions, classes, closures, memory model), the standard library by topic (strings, math, arrays, regex, time, files, SQLite) and the toolchain.",
    base: "",
    canonical: "docs.html",
    body,
    script,
  });
}

/* ---------------- main ---------------- */

const libs = loadLibraries();
write(path.join(DOCS, "libraries", "index.html"), libraryIndex(libs));
for (const lib of libs) write(path.join(DOCS, "libraries", lib.name, "index.html"), libraryPage(lib, libs));
for (const lib of libs) {
  const old = path.join(DOCS, `lib-${lib.name}.html`);
  if (fs.existsSync(old) && !/http-equiv="refresh"/.test(read(old))) {
    /* the content lives in docs/libraries/src now; keep the old URL working */
    write(old, redirectPage(`libraries/${lib.name}/`, lib.name));
  } else if (!fs.existsSync(old)) {
    write(old, redirectPage(`libraries/${lib.name}/`, lib.name));
  }
}
const sqliteOld = path.join(DOCS, "lib-sqlite.html");
if (fs.existsSync(sqliteOld) && !/http-equiv="refresh"/.test(read(sqliteOld))) {
  const sec = mainOf(read(sqliteOld)).replace(/<h1>[\s\S]*?<\/h1>/, "<h2>SQLite</h2>");
  write(path.join(SRC, "_sqlite.html"), `<!-- built-in SQLite: the SQLite tab of docs.html (scripts/gensite.js) -->\n${sec.trim()}\n`);
  write(sqliteOld, redirectPage("docs.html#sqlite", "sqlite"));
}
write(path.join(DOCS, "docs.html"), documentationPage());

/* sitemap: the library URLs are generated, everything else stays as written */
const smPath = path.join(DOCS, "sitemap.xml");
if (fs.existsSync(smPath)) {
  let sm = read(smPath).split("\n")
    .filter((l) => !/hphp\.ch\/(lib-[a-z]+\.html|libraries\/)/.test(l)).join("\n");
  const urls = ["libraries/", ...libs.map((l) => `libraries/${l.name}/`)]
    .map((u) => `  <url><loc>https://hphp.ch/${u}</loc></url>`).join("\n");
  sm = sm.replace("</urlset>", `${urls}\n</urlset>`);
  write(smPath, sm);
}
console.log(`gensite ok: ${libs.length} libraries, docs.html, redirects`);
