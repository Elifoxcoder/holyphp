  testing:   { rank: 3,  cat: "Tooling",          glyph: "✓",  tagline: "Assertions for hphp test with readable failure messages.", tags: ["test", "assert", "unit tests", "tdd"] },
  cli:       { rank: 4,  cat: "Tooling",          glyph: ">_", tagline: "Arguments, questions, tables, progress bars and colors.", tags: ["terminal", "console", "arguments", "flags", "ansi"] },
  thread:    { rank: 5,  cat: "Concurrency",      glyph: "∥",  tagline: "OS threads, channels, mutexes and a worker pool.", tags: ["threads", "parallel", "channels", "pool", "mutex"] },
  dotenv:    { rank: 6,  cat: "Tooling",          glyph: "⚙",  tagline: "Configuration from .env files and the environment.", tags: ["config", "environment", "settings", ".env"] },
  websocket: { rank: 7,  cat: "Web & networking", glyph: "⇄",  tagline: "WebSocket servers: handshake, frames, chat-style broadcasting.", tags: ["websocket", "realtime", "chat", "push"] },
  ui:        { rank: 8,  cat: "Desktop",          glyph: "▣",  tagline: "Native windows, widgets, menus, dialogs and themes.", tags: ["gui", "desktop", "windows", "widgets"] },
  html:      { rank: 9,  cat: "Desktop",          glyph: "</>", tagline: "Parse HTML and CSS, lay out and paint documents.", tags: ["html", "css", "layout", "dom", "render"] },
