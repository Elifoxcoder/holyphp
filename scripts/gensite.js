/* Tabs: buttons switch panels; the hash keeps the tab (#documentation).
 * Without JavaScript every panel is shown one after another. */
const TABS_JS = `
<script>
(function () {
  var root = document.querySelector("[data-tabs]");
  if (!root) return;
  var buttons = root.querySelectorAll("[data-tab-button]");
  var panels = root.querySelectorAll("[data-tab-panel]");
  root.classList.add("tabs-ready");
  function show(name, push) {
    var found = false;
    panels.forEach(function (p) { var on = p.getAttribute("data-tab-panel") === name; p.hidden = !on; if (on) found = true; });
    if (!found) return show(panels[0].getAttribute("data-tab-panel"), false);
    buttons.forEach(function (b) { var on = b.getAttribute("data-tab-button") === name; b.setAttribute("aria-selected", on ? "true" : "false"); b.classList.toggle("active", on); });
    if (push) history.replaceState(null, "", "#" + name);
    var side = document.querySelector(".doc-side");
    if (side) side.classList.remove("open");
  }
  buttons.forEach(function (b) { b.addEventListener("click", function (e) { e.preventDefault(); show(b.getAttribute("data-tab-button"), true); window.scrollTo({ top: 0 }); }); });
  window.addEventListener("hashchange", function () { show(location.hash.slice(1), false); });
  show(location.hash.slice(1) || panels[0].getAttribute("data-tab-panel"), false);
  window.__showTab = show;
})();
</script>`;

/* ---------------- libraries ---------------- */

function loadLibraries() {
  const libs = [];
  for (const name of Object.keys(LIBS)) {
    const mf = path.join(LIBDIR, name, "hphp.json");
    const src = path.join(SRC, `${name}.html`);
    if (!fs.existsSync(mf)) throw new Error(`gensite: ${mf} missing`);
    if (!fs.existsSync(src)) throw new Error(`gensite: ${src} missing (write the library page source)`);
    const manifest = JSON.parse(read(mf));
    const tabs = {};
    const text = read(src);
    for (const m of text.matchAll(/<section data-tab="([a-z]+)">([\s\S]*?)<\/section>/g)) tabs[m[1]] = m[2].trim();
    for (const t of ["overview", "documentation", "examples"])
      if (!tabs[t]) throw new Error(`gensite: ${src} has no <section data-tab="${t}">`);
    libs.push({ name, ...LIBS[name], version: manifest.version, description: manifest.description || "", require: manifest.require || {}, entry: manifest.entry, tabs });
  }
  /* every bundled library needs an entry above, so none is left without a page */
  for (const d of fs.readdirSync(LIBDIR)) {
    if (fs.existsSync(path.join(LIBDIR, d, "hphp.json")) && !LIBS[d])
      throw new Error(`gensite: packages/lib/${d} has no entry in LIBS (scripts/gensite.js)`);
  }
  return libs.sort((a, b) => a.rank - b.rank);
}

function installTab(lib) {
  const deps = Object.keys(lib.require);
  const depNote = deps.length
    ? `<p>It needs ${deps.map((d) => `<a href="../${d}/">${d}</a>`).join(", ")}; <code>hphp install</code> adds ${deps.length === 1 ? "it" : "them"} automatically.</p>`
    : "";
  return `<h2>In a project</h2>
<p>Inside a project (a folder with <code>hphp.yaml</code>, see <a href="../../pkg.html">Projects &amp; packages</a>):</p>
<pre><code class="bash">hphp install ${lib.name}</code></pre>
<p>This adds the library to <code>hphp.yaml</code>, installs it into <code>.hphp/packages/${lib.name}/</code> and pins the exact version in <code>hphp.lock</code>:</p>
<pre><code class="yaml">require:
  ${lib.name}: "^${lib.version.split(".").slice(0, 2).join(".")}"</code></pre>
${depNote}
<h2>Use it</h2>
<pre><code class="hphp">import "${lib.name}";</code></pre>
<p>${esc(lib.name)} is bundled with the compiler, so <code>import "${lib.name}";</code> also works in a single file without installing anything, and <code>hphp install</code> works offline.</p>
<h2>Outside a project</h2>
<pre><code class="bash">hphp install ${lib.name}          # for your user, shared by all scripts
hphp create myapp                 # or start a project, then: hphp install ${lib.name}</code></pre>
<table>
  <tr><th>Package</th><td><code>${lib.name}</code></td></tr>
  <tr><th>Version</th><td>${esc(lib.version)} (follows the compiler)</td></tr>
  <tr><th>Entry file</th><td><code>${esc(lib.entry || lib.name + ".hphp")}</code></td></tr>
  <tr><th>Source</th><td><a href="https://github.com/Elifoxcoder/holyphp/tree/main/packages/lib/${lib.name}" target="_blank" rel="noopener">packages/lib/${lib.name} ↗</a></td></tr>
</table>`;
}

